"""Normalisation and fully-tensorised genetic operators (Section 3.1).

Every population lives in the normalised hyper-cube ``[0, 1]^D`` with the 3-D
batched shape ``(B, N, D)``. All random numbers are drawn from an explicit
``torch.Generator`` (``torch.rand_like`` is avoided because it cannot take a
generator).
"""
from __future__ import annotations

import torch

Tensor = torch.Tensor


def _rand(shape, like: Tensor, generator: torch.Generator | None) -> Tensor:
    return torch.rand(shape, device=like.device, dtype=like.dtype, generator=generator)


def _randn(shape, like: Tensor, generator: torch.Generator | None) -> Tensor:
    return torch.randn(shape, device=like.device, dtype=like.dtype, generator=generator)


# --------------------------------------------------------------------------- bounds
def normalize(X_real: Tensor, xl: Tensor, xu: Tensor) -> Tensor:
    """Affine map ``[xl, xu] -> [0, 1]`` with clamping. ``xl, xu``: ``(1, 1, D)``."""
    return torch.clamp((X_real - xl) / (xu - xl + 1e-12), 0.0, 1.0)


def denormalize(Z: Tensor, xl: Tensor, xu: Tensor) -> Tensor:
    """Affine map ``[0, 1] -> [xl, xu]`` (input is clamped first)."""
    return xl + torch.clamp(Z, 0.0, 1.0) * (xu - xl)


def reflect_clamp(Z: Tensor) -> Tensor:
    """Reflective boundary handling: mirror out-of-range coordinates, then clamp.

    Avoids the boundary pile-up that plain clipping produces.
    """
    Z = torch.where(Z < 0.0, -Z, torch.where(Z > 1.0, 2.0 - Z, Z))
    return torch.clamp(Z, 0.0, 1.0)


# --------------------------------------------------------------------------- sampling
def uniform_population(B: int, N: int, D: int, *, device, dtype=torch.float32,
                       generator: torch.Generator | None = None) -> Tensor:
    return torch.rand((B, N, D), device=device, dtype=dtype, generator=generator)


def orthogonal_lhs(B: int, N: int, D: int, *, device, dtype=torch.float32,
                   generator: torch.Generator | None = None) -> Tensor:
    """Batched Latin-hypercube sample in ``[0, 1]^D``; shape ``(B, N, D)``.

    Each dimension receives an independent random permutation of the ``N``
    strata (generated by argsort of uniform keys, fully vectorised), plus a
    uniform jitter inside each stratum.
    """
    if N <= 0:
        return torch.empty((B, 0, D), device=device, dtype=dtype)
    keys = torch.rand((B, N, D), device=device, generator=generator)
    perm = torch.argsort(keys, dim=1).to(dtype)                    # (B, N, D) strata ids
    jitter = torch.rand((B, N, D), device=device, dtype=dtype, generator=generator)
    return (perm + jitter) / float(N)


# --------------------------------------------------------------------------- SBX
def batched_sbx(parents1: Tensor, parents2: Tensor, eta_c: float = 15.0, prob_c: float = 0.9,
                generator: torch.Generator | None = None) -> tuple[Tensor, Tensor]:
    """Bounded simulated binary crossover on ``[0, 1]^D``.

    Args:
        parents1, parents2: ``(B, P, D)`` normalised parents (``P = N // 2``).
    Returns:
        Two offspring tensors ``(B, P, D)`` clamped to ``[0, 1]``.
    """
    if parents1.shape != parents2.shape:
        raise ValueError("parents1 and parents2 must share shape (B, N//2, D)")
    B, P, D = parents1.shape
    do_cross = _rand((B, P, 1), parents1, generator) < prob_c
    do_dim = _rand((B, P, D), parents1, generator) <= 0.5
    distinct = torch.abs(parents1 - parents2) > 1e-14
    mask = do_cross & do_dim & distinct

    y1 = torch.minimum(parents1, parents2)
    y2 = torch.maximum(parents1, parents2)
    delta = torch.clamp(y2 - y1, min=1e-10)
    expo = eta_c + 1.0

    beta1 = 1.0 + (2.0 * (y1 - 0.0) / delta)
    beta2 = 1.0 + (2.0 * (1.0 - y2) / delta)
    alpha1 = 2.0 - torch.pow(beta1, -expo)
    alpha2 = 2.0 - torch.pow(beta2, -expo)

    u = _rand((B, P, D), parents1, generator)

    def _beta_q(alpha: Tensor) -> Tensor:
        ua = u * alpha
        return torch.where(
            u <= 1.0 / alpha,
            torch.pow(torch.clamp(ua, min=0.0), 1.0 / expo),
            torch.pow(1.0 / torch.clamp(2.0 - ua, min=1e-12), 1.0 / expo),
        )

    beta_q1 = _beta_q(alpha1)
    beta_q2 = _beta_q(alpha2)
    c1 = 0.5 * ((y1 + y2) - beta_q1 * (y2 - y1))
    c2 = 0.5 * ((y1 + y2) + beta_q2 * (y2 - y1))
    c1 = torch.clamp(c1, 0.0, 1.0)
    c2 = torch.clamp(c2, 0.0, 1.0)

    swap = _rand((B, P, D), parents1, generator) <= 0.5
    o1 = torch.where(swap, c2, c1)
    o2 = torch.where(swap, c1, c2)
    off1 = torch.where(mask, o1, parents1)
    off2 = torch.where(mask, o2, parents2)
    return torch.clamp(off1, 0.0, 1.0), torch.clamp(off2, 0.0, 1.0)


# --------------------------------------------------------------------------- PM
def batched_pm(Z: Tensor, eta_m: float = 20.0, prob_m: float | None = None,
               generator: torch.Generator | None = None) -> Tensor:
    """Bounded polynomial mutation in ``[0, 1]^D`` (default ``prob_m = 1 / D``)."""
    D = Z.shape[-1]
    if prob_m is None:
        prob_m = 1.0 / D
    mask = _rand(Z.shape, Z, generator) < prob_m
    u = _rand(Z.shape, Z, generator)
    delta1 = Z
    delta2 = 1.0 - Z
    mut_pow = 1.0 / (eta_m + 1.0)

    xy1 = 1.0 - delta1
    val1 = 2.0 * u + (1.0 - 2.0 * u) * torch.pow(xy1, eta_m + 1.0)
    dq1 = torch.pow(torch.clamp(val1, min=0.0), mut_pow) - 1.0

    xy2 = 1.0 - delta2
    val2 = 2.0 * (1.0 - u) + 2.0 * (u - 0.5) * torch.pow(xy2, eta_m + 1.0)
    dq2 = 1.0 - torch.pow(torch.clamp(val2, min=0.0), mut_pow)

    delta_q = torch.where(u <= 0.5, dq1, dq2)
    out = torch.where(mask, Z + delta_q, Z)
    return torch.clamp(out, 0.0, 1.0)


def gaussian_perturb(Z: Tensor, sigma: Tensor | float, generator: torch.Generator | None = None) -> Tensor:
    """Add ``N(0, sigma^2)`` noise (broadcastable ``sigma``) and reflect into the box."""
    return reflect_clamp(Z + _randn(Z.shape, Z, generator) * sigma)


def maybe_compile(fn, enabled: bool = False):
    """Optionally wrap ``fn`` with ``torch.compile`` (falls back silently).

    ``torch.compile`` needs a working Triton / C++ toolchain; on platforms where
    it is unavailable (e.g. Windows CPU) the eager function is returned.
    """
    if not enabled:
        return fn
    try:
        return torch.compile(fn, dynamic=True)
    except Exception:  # pragma: no cover - platform dependent
        return fn
